def fechas_por_dia(col, extra=None):
    # {(fecha, extra): [ids]}  -> agrupa slices/tiles del mismo día
    props = ["system:index", "system:time_start"] + ([extra] if extra else [])
    filas = col.reduceColumns(ee.Reducer.toList(len(props)), props).get("list").getInfo()
    g = defaultdict(list)
    for f in filas:
        d = datetime.fromtimestamp(f[1] / 1000, tz=timezone.utc).date()
        g[(d, f[2] if extra else None)].append(f[0])
    return dict(sorted(g.items()))

