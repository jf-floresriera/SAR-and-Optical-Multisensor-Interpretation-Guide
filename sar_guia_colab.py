# ---- Matemática de fase y polarimetría dual (Cloude 2007)
def matriz_c2(s_vv, s_vh, w=7):
    c12 = s_vv * np.conj(s_vh)
    return (uniform_filter(np.abs(s_vv)**2, w), uniform_filter(np.abs(s_vh)**2, w),
            uniform_filter(c12.real, w) + 1j * uniform_filter(c12.imag, w))

def h_alpha(c11, c22, c12):
    tr = c11 + c22
    d = np.sqrt(((c11 - c22) / 2)**2 + np.abs(c12)**2)
    lam = np.stack([tr/2 + d, np.maximum(tr/2 - d, 0)])
    a = np.abs(c12) + 1e-20
    alfa_i = np.degrees(np.arccos(np.clip(a / np.sqrt(a**2 + (lam - c11)**2), 0, 1)))
    p = lam / np.maximum(tr, 1e-20)
    H = -np.sum(np.where(p > 0, p * np.log2(np.maximum(p, 1e-20)), 0), axis=0)
    return H, np.sum(p * alfa_i, axis=0)

