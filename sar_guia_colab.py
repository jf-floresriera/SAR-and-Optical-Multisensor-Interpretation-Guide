_cache_nubes = {}
def nubes_aoi(ids):
    k = tuple(sorted(ids))
    if k not in _cache_nubes:
        scl = ee.ImageCollection([ee.Image(f"{COL_S2}/{i}") for i in ids]).mosaic().select("SCL")
        n = scl.eq(3).Or(scl.eq(8)).Or(scl.eq(9)).Or(scl.eq(10)).rename("n")
        v = n.reduceRegion(ee.Reducer.mean(), aoi, 20, maxPixels=1e9).get("n").getInfo()
        _cache_nubes[k] = 100.0 if v is None else 100 * v
    return _cache_nubes[k]

def fecha_mosaico_anual(anio):
    # Respaldo: mediana de la banda de fecha (días desde lanzamiento ALOS-2, 2014-05-24)
    img = ee.ImageCollection(COL_ALOS_ANUAL).filterDate(f"{anio}-01-01", f"{anio}-12-31").first()
    bandas = img.bandNames().getInfo()
    b = next((x for x in bandas if x.lower() in ("date", "epoch", "obs_date")), None)
    if b is None:
        return date(anio, 7, 1)
    dias = img.select(b).reduceRegion(ee.Reducer.median(), aoi, 25).get(b).getInfo()
    return date(2014, 5, 24) + timedelta(days=int(dias))

def por_fecha(grupos, d):
    # ids de una fecha; en S1 se toma la órbita con más escenas ese día
    cands = [(k, v) for k, v in grupos.items() if k[0] == d]
    if not cands:
        raise ValueError(f"No hay escenas el {d}")
    k, v = max(cands, key=lambda kv: len(kv[1]))
    return k, v

