"""---
# FASE 2 · PROCESAMIENTO
### Física y matemática aplicada
* **ALOS-2:** γ⁰ = DN² · 10^(K/10), K = −83 dB  ⇔  γ⁰[dB] = 10·log₁₀(DN²) − 83
* **Sentinel-1:** γ⁰ = σ⁰ / cos θ (θ = ángulo elipsoidal; normaliza near/far range, **no** es RTC completa) llevar a RTC la colección OJO
* **Speckle** multiplicativo I = R·n, Var[n] = 1/ENL → filtro de Lee: R̂ = m + k(I − m), k = max(0, 1 − C²ᵤ/C²ᵢ)
* **Regla de oro:** promediar y remuestrear en **potencia lineal**; pasar a dB al final. Cociente co/cross = resta en dB.
* **Sentinel-2:** ρ = DN/10 000; nubes enmascaradas con SCL; NDVI = (NIR − R)/(NIR + R)
"""

import rasterio
from rasterio.warp import reproject, Resampling
from scipy.ndimage import uniform_filter

# ---------- E/S raster
def leer(ruta):
    with rasterio.open(ruta) as ds:
        return ds.read().astype("float64"), ds.profile.copy()

def reproyectar(arr, p_src, p_ref, metodo="bilinear"):
    arr = arr[None] if arr.ndim == 2 else arr
    dst = np.full((arr.shape[0], p_ref["height"], p_ref["width"]), np.nan)
    for b in range(arr.shape[0]):
        reproject(arr[b], dst[b], src_transform=p_src["transform"], src_crs=p_src["crs"],
                  dst_transform=p_ref["transform"], dst_crs=p_ref["crs"],
                  src_nodata=np.nan, dst_nodata=np.nan, resampling=getattr(Resampling, metodo))
    return dst

def escribir(ruta, arr, p_ref, desc, dtype="float32", nodata=np.nan):
    arr = arr[None] if arr.ndim == 2 else arr
    p = p_ref.copy()
    p.update(driver="GTiff", count=arr.shape[0], dtype=dtype, nodata=nodata, compress="deflate")
    with rasterio.open(ruta, "w", **p) as ds:
        ds.write(arr.astype(dtype))
        for i, d in enumerate(desc, 1):
            ds.set_band_description(i, d)

# ---------- Radiometría
def alos_dn_a_lineal(dn):
    out = dn ** 2 * 10 ** (K_ALOS_DB / 10); out[~(dn > 0)] = np.nan; return out
def a_db(lin):   return 10 * np.log10(np.where(lin > 0, lin, np.nan))
def media_db(l): return float(10 * np.log10(np.nanmean(l)))
def std_db(l):   return float(np.nanstd(a_db(l)))

# ---------- Speckle
def lee(img, w=LEE_VENTANA, enl=LEE_ENL):
    mask = ~np.isfinite(img)
    x = np.where(mask, np.nanmedian(img), img)
    m = uniform_filter(x, w)
    var = np.maximum(uniform_filter(x * x, w) - m * m, 0)
    k = np.clip(1 - (1 / enl) / np.maximum(var / np.maximum(m * m, 1e-12), 1e-12), 0, 1)
    out = m + k * (x - m); out[mask] = np.nan
    return out

def enl_estimado(img, w=9):
    x = np.nan_to_num(img); m = uniform_filter(x, w); v = uniform_filter(x * x, w) - m * m
    return float(np.nanmedian((m * m / np.maximum(v, 1e-12))[m > 0]))

# ---------- Color
def estirar(x, p=PERCENTILES_VIS):
    lo, hi = np.nanpercentile(x, p); return np.clip((x - lo) / max(hi - lo, 1e-9), 0, 1)
def rgb_sar(co_db, cx_db):
    return np.dstack([estirar(co_db), estirar(cx_db), estirar(co_db - cx_db)])
def a_uint8(rgb):
    return (np.nan_to_num(rgb) * 254 + 1).astype("uint8").transpose(2, 0, 1)
print("✅ Funciones de procesamiento cargadas")

