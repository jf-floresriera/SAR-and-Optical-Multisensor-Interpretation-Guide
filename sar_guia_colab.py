for n, b in (("B2", b2), ("B3", b3), ("B4", b4), ("B8", b8)):
    r = b / 10000.0; r[(b == 0) | nube] = np.nan; REF[n] = r
NDVI = (REF["B8"] - REF["B4"]) / (REF["B8"] + REF["B4"])

